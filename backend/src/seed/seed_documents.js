/**
 * Seeds course materials that can actually be opened.
 *
 * Document records used to be created ad-hoc during testing with placeholder
 * paths like `/uploads/test.pdf` — files nobody ever wrote. The record looked
 * fine in the database and the Documents tab listed it, but every view or
 * download 404'd, because the bytes never existed. (The Atlas theory in the
 * issue sheet was a red herring: the same records 404 against a purely local
 * database.)
 *
 * So this writes the PDF first and derives the record from what it actually
 * wrote. A document row here cannot reference a file that is not on disk.
 */

function writePdf(absPath, { title, lines }) {
  return new Promise((resolve, reject) => {
    const doc = new PDFDocument({ margin: 50 });
    const stream = fs.createWriteStream(absPath);
    doc.pipe(stream);

    doc.fontSize(20).text(title, { underline: true });
    doc.moveDown();
    doc.fontSize(12);
    for (const line of lines) {
      doc.text(line);
      doc.moveDown(0.4);
    }
    doc.moveDown();
    doc.fontSize(9).fillColor('#666').text(`${env.SCHOOL_NAME} — sample course material generated by the seeder.`);
    doc.end();

    stream.on('finish', resolve);
    stream.on('error', reject);
  });
}

