#!/usr/bin/env node
/**
 * Regenerates src/modules/ai/studyBuddy/skillPrompt.generated.js from the
 * Student Learning Buddy source package.
 *
 *   cd backend && node scripts/sync-learning-buddy.mjs
 *
 * Why a generated copy rather than reading the package at runtime: the backend
 * image is built from ./backend alone and esbuild bundles src/, so
 * ../ai-skills does not exist in production. A copy that works locally and is
 * missing in the container is the worst kind of failure.
 *
 * Why a script rather than hand-copying: the prompt carries Indic scripts,
 * Urdu and typographic quotes. Pasting it through an editor or a shell heredoc
 * is how bytes get mangled. Here the file is read as UTF-8 and embedded with
 * JSON.stringify, which round-trips every code point exactly.
 *
 * The package is read-only. This script refuses to run if the prompt no longer
 * matches the checksum its own MANIFEST.json declares, so a half-edited package
 * cannot be synced by accident. tests/studyHelp.skillSync.test.js fails if the
 * generated copy drifts from the package.
 */
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const backendRoot = join(here, '..');
const packageRoot = join(backendRoot, '..', 'ai-skills', 'Student_Learning_Buddy_Universal_Skill_v3');
const promptFile = 'UNIVERSAL_SYSTEM_PROMPT.txt';
const outFile = join(backendRoot, 'src', 'modules', 'ai', 'studyBuddy', 'skillPrompt.generated.js');

const manifest = JSON.parse(readFileSync(join(packageRoot, 'MANIFEST.json'), 'utf8'));
const bytes = readFileSync(join(packageRoot, promptFile));
const sha256 = createHash('sha256').update(bytes).digest('hex');

const declared = manifest.files?.[promptFile]?.sha256;
if (declared !== sha256) {
  console.error(`${promptFile} does not match MANIFEST.json (${sha256} vs ${declared}). Refusing to sync.`);
  process.exit(1);
}

const text = bytes.toString('utf8');
const source = `// GENERATED by backend/scripts/sync-learning-buddy.mjs — do not edit by hand.
// Source: ${relative(backendRoot, join(packageRoot, promptFile)).split('\\').join('/')}
// Re-run the script after the package changes; tests/studyHelp.skillSync.test.js
// fails while this copy and the package disagree.

export const SKILL_NAME = ${JSON.stringify(manifest.name)};
export const SKILL_VERSION = ${JSON.stringify(manifest.version)};
export const SKILL_PROMPT_SHA256 = ${JSON.stringify(sha256)};

export const SKILL_PROMPT = ${JSON.stringify(text)};
`;

writeFileSync(outFile, source, 'utf8');
console.log(`Wrote ${relative(backendRoot, outFile)} — ${manifest.name} v${manifest.version}, ${bytes.length} bytes, sha256 ${sha256}`);
